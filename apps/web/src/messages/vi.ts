export function t(template: string, vars: Record<string, string>): string {
	return template.replace(
		/\{([^{}]+)\}/g,
		(placeholder: string, key: string) =>
			Object.hasOwn(vars, key) ? (vars[key] ?? placeholder) : placeholder,
	);
}
